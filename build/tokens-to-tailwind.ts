// Generates web/src/design/tokens.css and web/tailwind.preset.ts from design-package/project/tokens.json
// (spec §10.1–10.2: every token 1:1 to a CSS variable; Tailwind reads only the variables).
// Run: node build/tokens-to-tailwind.ts   (Node 22 strips the types)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type StateToken = { label: string; solid?: string; soft?: string; "text-on-soft"?: string; outline?: string };
type TypeRole = { size: number; weight: number; lineHeight: number };

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design-package/project/tokens.json"), "utf8"));
const HEADER = "Generated by build/tokens-to-tailwind.ts from design-package/project/tokens.json — do not edit.";

const css: string[] = [];
const colors: Record<string, unknown> = {};
const stateColors: Record<string, Record<string, string>> = {};

for (const [name, value] of Object.entries(tokens.color as Record<string, unknown>)) {
  if (name === "state") continue;
  css.push(`  --color-${name}: ${value};`);
  colors[name] = `var(--color-${name})`;
}
for (const [state, t] of Object.entries(tokens.color.state as Record<string, StateToken>)) {
  const parts: Record<string, string> = {};
  const add = (key: string, suffix: string, value?: string) => {
    if (!value) return;
    const variable = `--color-state-${state}${suffix}`;
    css.push(`  ${variable}: ${value};`);
    parts[key] = `var(${variable})`;
  };
  add("DEFAULT", "", t.solid ?? t.outline);
  add("soft", "-soft", t.soft);
  add("text", "-text", t["text-on-soft"]);
  stateColors[state] = parts;
}
colors.state = stateColors;

// Feedback soft/text shades: the artboards use the state shades with the same values for semantic
// feedback (RTL notes, exception 2), but tokens.json names only the solids. Design gap 8.
const FEEDBACK_FROM_STATE: Record<string, string> = {
  success: "ready",
  warning: "cleaning",
  danger: "overdue",
  info: "occupied",
};
for (const [feedback, state] of Object.entries(FEEDBACK_FROM_STATE)) {
  const t = tokens.color.state[state] as StateToken;
  css.push(`  --color-${feedback}-soft: ${t.soft};`, `  --color-${feedback}-text: ${t["text-on-soft"]};`);
  colors[`${feedback}-soft`] = `var(--color-${feedback}-soft)`;
  colors[`${feedback}-text`] = `var(--color-${feedback}-text)`;
}

const typography = tokens.typography;
css.push(`  --font-family: "${typography.family}", "${typography.fallback}", sans-serif;`);
const fontSize: Record<string, [string, { lineHeight: string; fontWeight: string }]> = {};
for (const [role, value] of Object.entries(typography as Record<string, unknown>)) {
  if (typeof value !== "object") continue;
  const t = value as TypeRole;
  css.push(`  --text-${role}: ${t.weight} ${t.size}px/${t.lineHeight}px var(--font-family);`);
  fontSize[role] = [`${t.size}px`, { lineHeight: `${t.lineHeight}px`, fontWeight: String(t.weight) }];
}

const borderRadius: Record<string, string> = {};
for (const [name, px] of Object.entries(tokens.radius as Record<string, number>)) {
  css.push(`  --radius-${name}: ${px}px;`);
  borderRadius[name] = `var(--radius-${name})`;
}
const boxShadow: Record<string, string> = {};
for (const [name, value] of Object.entries(tokens.shadow as Record<string, string>)) {
  css.push(`  --shadow-${name}: ${value};`);
  boxShadow[name] = `var(--shadow-${name})`;
}
const ring = tokens.focusRing;
css.push(`  --focus-ring-width: ${ring.width}px;`, `  --focus-ring-offset: ${ring.offset}px;`);
css.push(`  --color-focus-ring: ${ring.color};`);
colors["focus-ring"] = "var(--color-focus-ring)";

const size = tokens.size;
const spacing: Record<string, string> = {};
const px = (name: string, value: number) => {
  css.push(`  --size-${name}: ${value}px;`);
  spacing[name] = `var(--size-${name})`;
};
px("table-row", size.tableRow);
px("card-padding", size.cardPadding);
px("button", size.button[0]);
px("button-lg", size.button[1]);
px("topbar", size.topBar);
px("sidebar", size.sidebar);
px("sidebar-rail", size.sidebarRail);
px("drawer", size.drawer);
px("room-card-w", size.roomCard[0]);
px("room-card-h", size.roomCard[1]);
px("icon", tokens.icon.control);
px("icon-inline", tokens.icon.inline);
css.push(`  --icon-stroke: ${tokens.icon.stroke};`);

writeFileSync(join(root, "web/src/design/tokens.css"), `/* ${HEADER} */\n:root {\n${css.join("\n")}\n}\n`);

const preset = {
  theme: {
    extend: {
      colors,
      fontFamily: { sans: ["var(--font-family)"] },
      fontSize,
      borderRadius,
      boxShadow,
      spacing,
      width: spacing,
      height: spacing,
    },
  },
};
writeFileSync(
  join(root, "web/tailwind.preset.ts"),
  `// ${HEADER}\nimport type { Config } from "tailwindcss";\n\nconst preset: Partial<Config> = ${JSON.stringify(preset, null, 2)};\n\nexport default preset;\n`,
);
console.log("tokens.css and tailwind.preset.ts written");
